/* =============================================================================
 * build.mjs — two esbuild bundles, zero configuration:
 *   assets/app.js             the course app (classic script → works from file://)
 *   assets/harness-inline.js  the exercise runtime, stored as a JS string so it
 *                             can be inlined into every sandbox srcdoc
 * ========================================================================== */

import { build } from 'esbuild'
import { readFile, writeFile, mkdir, rm } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const watch = process.argv.includes('--watch')

const banner = `/* learn-alpine — generated by scripts/build.mjs. Edit src/, not this file. */`

const common = {
  bundle: true,
  target: ['chrome90', 'firefox90', 'safari15'],
  legalComments: 'none',
  logLevel: 'info',
  sourcemap: false
}

async function buildApp() {
  await build({
    ...common,
    entryPoints: [join(root, 'src/app.js')],
    outfile: join(root, 'assets/app.js'),
    format: 'iife',
    banner: { js: banner }
  })
}

async function buildHarness() {
  await mkdir(join(root, 'assets'), { recursive: true })
  const tmp = join(root, 'assets/.harness.tmp.js')
  await build({
    ...common,
    entryPoints: [join(root, 'src/harness/index.js')],
    outfile: tmp,
    format: 'iife',
    minify: true
  })
  const src = await readFile(tmp, 'utf8')
  const escaped = JSON.stringify(src).replace(/<\/script/gi, '<\\/script')
  await writeFile(
    join(root, 'assets/harness-inline.js'),
    `${banner}\nwindow.__LA_HARNESS_SRC = ${escaped};\n`
  )
  await rm(tmp, { force: true })
  console.log(`harness inlined: ${(src.length / 1024).toFixed(0)} kB`)
}

if (watch) {
  const { context } = await import('esbuild')
  const ctx = await context({
    ...common,
    entryPoints: [join(root, 'src/app.js')],
    outfile: join(root, 'assets/app.js'),
    format: 'iife',
    banner: { js: banner }
  })
  await ctx.watch()
  console.log('watching src/ → assets/app.js')
  // The harness changes rarely; rebuild it once at startup.
  await buildHarness()
} else {
  await buildApp()
  await buildHarness()
  console.log('built assets/app.js and assets/harness-inline.js')
}
