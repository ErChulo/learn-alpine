/* =============================================================================
 * standalone.mjs — build a single-file version of the course:
 *
 *   learn-alpine.html   double-click it, no server, no folder, no network.
 *
 * Everything is inlined: the stylesheet (with the reading fonts as base64
 * data URIs), the app bundle, the sandbox runtime, and the vendored Alpine
 * builds that the "installation" lesson's raw-mode sandboxes expect to load
 * with a <script src> tag.
 * ========================================================================== */

import { readFile, writeFile, stat } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(root, 'learn-alpine.html')

const read = p => readFile(join(root, p), 'utf8')
const kb = n => (n / 1024).toFixed(0) + ' kB'

/* --------------------------------------------------------------- assets ---- */
const html = await read('index.html')
let css = await read('styles.css')
const harnessRaw = await read('assets/harness-inline.js')
const appRaw = await read('assets/app.js')

// The readable bundles stay on disk for the hosted build; the single file gets
// minified copies so a double-clicked document is not 3 MB of prose. esbuild is
// a devDependency, so fall back to the readable bundles when it is absent.
let minify = async code => code
try {
  const { transform } = await import('esbuild')
  minify = async code => (await transform(code, { minify: true, legalComments: 'none', target: 'chrome90', loader: 'js' })).code
} catch (e) {
  console.warn('esbuild not installed — writing the unminified bundles into the single file')
}
const harness = await minify(harnessRaw)
const appMin = await minify(appRaw)

const VENDOR_FILES = [
  'mask.min.js', 'intersect.min.js', 'persist.min.js', 'resize.min.js', 'collapse.min.js',
  'focus.min.js', 'morph.min.js', 'anchor.min.js', 'sort.min.js', 'cdn.min.js'
]
const vendor = {}
for (const f of VENDOR_FILES) vendor[f] = await read('vendor/alpine/' + f)

/* ---------------------------------------------------------------- fonts ---- */
let fontBytes = 0
const fontRefs = [...css.matchAll(/url\((['"]?)\.\/fonts\/([^)'"]+)\1\)/g)]
for (const m of fontRefs) {
  const file = m[2]
  const buf = await readFile(join(root, 'fonts', file))
  fontBytes += buf.length
  const b64 = buf.toString('base64')
  const mime = file.endsWith('.woff2') ? 'font/woff2' : 'font/woff'
  css = css.replace(m[0], `url("data:${mime};base64,${b64}")`)
}

/* ------------------------------------------------------------ assembly ---- */
// Inline scripts must not contain a literal `</script` — neither bundle does,
// but escape defensively so a future dependency cannot break the file.
const safe = s => s.replace(/<\/script/gi, '<\\/script')

const vendorJson = JSON.stringify(vendor).replace(/<\//g, '<\\/')

// NOTE: every replacement uses a *function*. A replacement string would have its
// `$&`, `$\`` and `$'` sequences expanded — and CSS/JS full of `$` would then
// inject copies of the document into itself.
let out = html
  .replace(/\s*<link rel="stylesheet"[^>]*>/, () => '\n<style>\n' + css + '\n</style>')
  .replace(/\s*<script src="\.\/assets\/harness-inline\.js" defer><\/script>/, () => '')
  .replace(/\s*<script src="\.\/assets\/app\.js" defer><\/script>/, () => '')

const standaloneScripts = `
<!-- =====================================================================
     single-file build: the runtime, the vendored Alpine builds and the app
     are inlined below, so this document works from file:// with no server.
     ===================================================================== -->
<script>window.__LA_VENDOR_INLINE = ${vendorJson};</script>
<script>${safe(harness)}</script>
<script>${safe(appMin)}</script>
`
if (!out.includes('</body>')) throw new Error('index.html has no </body> to attach the scripts to')
out = out.replace(/\s*<\/body>/, () => standaloneScripts + '\n</body>')

// A note for anyone who opens the file in a text editor.
out = out.replace('<!DOCTYPE html>', () => `<!DOCTYPE html>
<!--
  learn-alpine — single-file build (generated by scripts/standalone.mjs).
  Save this file anywhere and double-click it. No server, no build step, no network.
  Progress is kept in this browser's localStorage (in-memory if storage is blocked).
-->`)

await writeFile(OUT, out)
const size = (await stat(OUT)).size
console.log(`learn-alpine.html  ${kb(size)}  (fonts ${kb(fontBytes)} as data URIs, vendor ${kb(Object.values(vendor).join('').length)}, app ${kb(appMin.length)}, harness ${kb(harness.length)})`)
